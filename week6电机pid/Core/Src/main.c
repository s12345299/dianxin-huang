float PID_Calculate(float setpoint,float measurement)//pid函数，setpoint为设定值，measurement为反馈值
{
	float error=setpoint-measurement;
	pid_integral+=error;//I项
	if(pid_integral>1000)pid_integral=1000;
	if(pid_integral<-1000)pid_integral=-1000;//积分限幅为-1000到1000
	float derivative=error-pid_previous_error;//D项
	pid_output=pid_Kp*error+pid_Ki*pid_integral+pid_Kd*derivative;
	if(pid_output>1000)pid_output=1000;//输出限幅，虽然但是好像没什么用
	if(pid_output<0)pid_output=0;
	return pid_output;
}
void PID_Reset(void)//pid重置，给按键和电机用的
{
	pid_integral=0;
	pid_previous_error=0;
	pid_output=0;
}
int32_t Read_Encoder(void)//读取编码器
{
	return(int32_t)(__HAL_TIM_GET_COUNTER(&htim3));
}
void Motor_Forward(uint16_t speed)//转动
{
	HAL_GPIO_WritePin(GPIOA,GPIO_PIN_4,GPIO_PIN_SET);
	HAL_GPIO_WritePin(GPIOA,GPIO_PIN_5,GPIO_PIN_RESET);
	__HAL_TIM_SET_COMPARE(&htim1,TIM_CHANNEL_1,speed);
}
void Motor_Stop(void)//不转
{
	HAL_GPIO_WritePin(GPIOA,GPIO_PIN_4,GPIO_PIN_RESET);
	HAL_GPIO_WritePin(GPIOA,GPIO_PIN_5,GPIO_PIN_RESET);
	__HAL_TIM_SET_COMPARE(&htim1,TIM_CHANNEL_1,0);
	current_speed_rps=0;
	PID_Reset();
}
float Calculate_Speed(void)//速度计算函数
{
	static uint32_t last_time=0;
	uint32_t current_time=HAL_GetTick();
	if(current_time-last_time<100)//自检是否有变化
	{
		return current_speed_rps;
	}
	last_time =current_time;
	encoder_value=Read_Encoder();
	int32_t encoder_diff=encoder_value-last_encoder_value;
	last_encoder_value=encoder_value;
	if(encoder_diff>32767)encoder_diff-=65536;//处理溢出
	if(encoder_diff<-32767)encoder_diff+=65536;
	current_speed_rps=(encoder_diff/0.1f)/1040.0f;//我用的是MG310霍尔编码器
	return current_speed_rps;
}
void Key(void)//按键
{
	if(HAL_GPIO_ReadPin(GPIOB,GPIO_PIN_1)==GPIO_PIN_RESET)
	{
		HAL_Delay(50);
		if(HAL_GPIO_ReadPin(GPIOB,GPIO_PIN_1)==GPIO_PIN_RESET)
		{
			float old_target=target_speed_rps;
			speed_mode=(speed_mode+1)%4;
			switch(speed_mode)
			{
				case 0:target_speed_rps=0.0f;
				break;
				case 1:target_speed_rps=1.0f;
				break;
				case 2:target_speed_rps=2.0f;
				break;
				case 3:target_speed_rps=3.0f;
				break;
			}
			PID_Reset();
		}
		while(HAL_GPIO_ReadPin(GPIOB,GPIO_PIN_1)==GPIO_PIN_RESET);
	}
}
void Control_Motor_Speed(void)//速度控制
{
	static uint32_t last_control_time=0;
	uint32_t current_time=HAL_GetTick();
	if(current_time-last_control_time<100)//自检是否有变化
	{
		return ;
	}
	last_control_time =current_time;
	Calculate_Speed();
	if(target_speed_rps==0)
	{
		Motor_Stop();
		return;
	}
	float output=PID_Calculate(target_speed_rps,current_speed_rps);
	Motor_Forward((uint16_t)output);
}
